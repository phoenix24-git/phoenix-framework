def F(name, type_, default=None, doc=""):
    return {"name": name, "type": type_, "default": default, "doc": doc}


def C(name, category, fields=(), unity=None, status="DataOnly", doc="", manual=False):
    """manual=True: defined and registered by hand in C++ (listed here for the docs only)."""
    return {"name": name, "category": category, "fields": list(fields), "unity": unity or name,
            "status": status, "doc": doc, "manual": manual}


