"""Generates Phoenix's built-in components from components/catalogue.py.

  gen_components.py --out <dir>            C++: phoenix/scene/components.gen.h + components.gen.cpp
  gen_components.py --docs <file.md>       docs/components.md (Unity -> Phoenix table)
"""
from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent

TYPES = {
    "bool": "bool", "int": "std::int32_t", "uint": "std::uint32_t", "long": "std::int64_t",
    "ulong": "std::uint64_t", "float": "float", "double": "double",
    "Vector2": "::Vector2", "Vector3": "::Vector3", "Vector4": "::Vector4", "Quaternion": "::Quaternion",
    "Color": "::Color", "Transform3D": "::Transform3D", "Entity": "Entity", "Asset": "AssetRef",
    "LayerMask": "LayerMask", "String": "::String", "StringName": "::StringName",
    "float[]": "::Vector<float>", "Vector3[]": "::Vector<::Vector3>", "Asset[]": "::Vector<AssetRef>",
    "Entity[]": "::Vector<Entity>",
}
HEADER = "// Generated by engine/components/gen_components.py from catalogue.py. Do not edit.\n"


def load_catalogue():
    spec = importlib.util.spec_from_file_location("catalogue", HERE / "catalogue.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def cpp_type(t: str) -> str:
    if t.startswith("enum:"):
        return t[5:]
    if t not in TYPES:
        raise SystemExit(f"unknown field type {t!r}")
    return TYPES[t]


def gen_header(cat) -> str:
    out = [HEADER, "#pragma once\n", '#include "phoenix/ecs/component.h"\n',
           "namespace phoenix::scene {\n",
           "using ecs::AssetRef;\nusing ecs::Entity;\nusing ecs::LayerMask;\n"]
    for name, values in cat.ENUMS.items():
        out.append(f"enum class {name} : std::int32_t {{ {', '.join(values)} }};")
    out.append("")
    current = None
    for c in cat.COMPONENTS:
        if c["manual"]:
            continue
        if c["category"] != current:
            current = c["category"]
            out.append(f"// {'-' * 90}\n// {current}\n// {'-' * 90}\n")
        doc = f" {c['doc']}" if c["doc"] else ""
        out.append(f"/// Unity: {c['unity']} ({c['status']}).{doc}")
        if not c["fields"]:
            out.append(f"struct {c['name']} {{}};\n")
            continue
        out.append(f"struct {c['name']} {{")
        for f in c["fields"]:
            init = f" = {f['default']}" if f["default"] is not None else "{}"
            comment = f"  ///< {f['doc']}" if f["doc"] else ""
            out.append(f"    {cpp_type(f['type'])} {f['name']}{init};{comment}")
        out.append("};\n")
    out.append("/// Registers every built-in component with the ECS ComponentRegistry (idempotent).")
    out.append("void register_builtin_components();")
    out.append(f"inline constexpr int kBuiltinComponentCount = {len(cat.COMPONENTS)};  // incl. manual\n")
    out.append("}  // namespace phoenix::scene")
    return "\n".join(out) + "\n"


def gen_source(cat) -> str:
    out = [HEADER, '#include "phoenix/scene/components.gen.h"\n',
           "namespace phoenix::scene {\n", "namespace {"]
    for name, values in cat.ENUMS.items():
        names = ", ".join(f'"{v}"' for v in values)
        out.append(f"const char* const k{name}Names[] = {{{names}, nullptr}};")
    out.append("}  // namespace\n")
    out.append("void register_builtin_components() {")
    out.append("    using ecs::ComponentStatus;")
    out.append("    using ecs::FieldInfo;")
    out.append("    auto& r = ecs::ComponentRegistry::instance();")
    for c in cat.COMPONENTS:
        if c["manual"]:
            continue
        n = c["name"]
        out.append("    {")
        out.append("        LocalVector<FieldInfo> fields;")
        for f in c["fields"]:
            out.append(f"        fields.push_back(PHX_FIELD({n}, {f['name']}));")
            if f["type"].startswith("enum:"):
                out.append(f"        fields[fields.size() - 1].enum_names = k{f['type'][5:]}Names;")
        status = "ComponentStatus::Simulated" if c["status"] == "Simulated" else "ComponentStatus::DataOnly"
        doc = c["doc"].replace('"', '\\"')
        out.append(f'        r.register_component<{n}>("{n}", "{c["category"]}", std::move(fields), {status}, '
                   f'"{c["unity"]}", "{doc}");')
        out.append("    }")
    out.append("}\n")
    out.append("}  // namespace phoenix::scene")
    return "\n".join(out) + "\n"


def gen_docs(cat) -> str:
    simulated = sum(1 for c in cat.COMPONENTS if c["status"] == "Simulated")
    lines = ["---", "title: Unity components", "nav_order: 5", "---", "",
             "# Unity components in Phoenix", "{: .no_toc }", "",
             "Every built-in Unity component has a Phoenix equivalent: a plain data struct stored in the",
             "data-oriented ECS (archetype chunks), reflected for serialization, prefabs and the inspector,",
             "and reachable through the Unity-style API (`GameObject`, `AddComponent<T>()`, `GetComponent<T>()`).",
             "Scripts derive from **`MetaBehaviour`** (Phoenix's `MonoBehaviour`).", "",
             f"**{len(cat.COMPONENTS)} components**: {simulated} simulated today, {len(cat.COMPONENTS) - simulated} "
             "data-only. Data-only components are fully usable as data (add, edit, save, query from systems);",
             "their built-in behaviour lands with the server that owns it (physics, rendering, audio, …).", "",
             "{: .note }",
             "Vector/math types are the Phoenix foundation types (`Vector3`, `Quaternion`, `Color`, `Transform3D`),",
             "in a right-handed, Y-up, −Z-forward space. The Unity importer converts Unity's left-handed data.", "",
             "_Generated from `engine/components/catalogue.py` — edit that file, not this page._", "",
             "1. TOC", "{:toc}", ""]
    current = None
    for c in cat.COMPONENTS:
        if c["category"] != current:
            current = c["category"]
            lines += ["", f"## {current}", "", "| Unity | Phoenix | Status | Fields |", "|---|---|---|---|"]
        fields = ", ".join(f"`{f['name']}`" for f in c["fields"]) or "—"
        status = "✅ simulated" if c["status"] == "Simulated" else "data"
        lines.append(f"| {c['unity']} | `{c['name']}` | {status} | {fields} |")
    lines += ["", "## Not runtime components", "",
              "Entries in Unity's lists that are assets, internals or duplicates, and where they live in Phoenix:", "",
              "| Unity | In Phoenix |", "|---|---|"]
    lines += [f"| {a} | {b} |" for a, b in cat.NOT_COMPONENTS]
    return "\n".join(lines) + "\n"


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--out", type=Path)
    p.add_argument("--docs", type=Path)
    args = p.parse_args()
    cat = load_catalogue()
    names = [c["name"] for c in cat.COMPONENTS]
    dupes = {n for n in names if names.count(n) > 1}
    if dupes:
        raise SystemExit(f"duplicate component names: {sorted(dupes)}")
    if args.out:
        d = args.out / "phoenix" / "scene"
        d.mkdir(parents=True, exist_ok=True)
        (d / "components.gen.h").write_text(gen_header(cat))
        (d / "components.gen.cpp").write_text(gen_source(cat))
    if args.docs:
        args.docs.write_text(gen_docs(cat))
    return 0


if __name__ == "__main__":
    sys.exit(main())
